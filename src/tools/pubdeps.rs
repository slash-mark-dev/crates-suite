//! Public Dependency Leak: Dependency types exposed in your public API, so their breaking release becomes yours.

use std::collections::{BTreeMap, BTreeSet};

use serde_json::json;

use crate::cli::{Args, Opt};
use crate::ctx::Ctx;
use crate::error::Result;
use crate::registry::index;
use crate::report::{Finding, Report, Severity, Table};
use crate::tools::apieco_util::{self, ItemKind, Surface, Vis, base_type_name};
use crate::tools::{Group, Tool};
use crate::util;

pub struct PubDeps;

const OPTS: &[Opt] = &[
    Opt::value("package", "NAME", "Workspace member to analyze (default: every library member)"),
    Opt::value("only", "A,B", "Only report these dependencies"),
    Opt::value("max-items", "N", "Exposure sites listed per dependency (default 5)"),
];

/// One place where a dependency's item appears in the public API.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Exposure {
    /// Extern crate name of the dependency.
    pub dep: String,
    /// `re-export`, `signature`, `field`, `impl`, `bound`, `type`.
    pub kind: &'static str,
    /// The public item that exposes it.
    pub item: String,
    pub file: String,
    pub line: usize,
    /// Full path of the dependency item (`url::Url`).
    pub path: String,
}

impl Tool for PubDeps {
    fn name(&self) -> &'static str {
        "pubdeps"
    }
    fn title(&self) -> &'static str {
        "Public Dependency Leak"
    }
    fn group(&self) -> Group {
        Group::Api
    }
    fn summary(&self) -> &'static str {
        "Dependency types exposed in your public API, so their breaking release becomes yours"
    }
    fn usage(&self) -> &'static str {
        "[CRATE[@VERSION]...] [OPTIONS]"
    }
    fn about(&self) -> &'static str {
        "Finds every place where a dependency's types or traits are part of a library's public API. When a
dependency is public, upgrading it to a new incompatible release (a new major, or a new 0.x minor) is
a breaking change for your users too, and users must use the exact same version of it to interoperate.

The public surface is modelled from source with a Rust lexer (no compilation): the module tree from
the library root (`mod x;` as x.rs, x/mod.rs or #[path], and inline modules), item visibility (an item
is public when it is `pub` and every enclosing module is `pub`, or when a reachable module re-exports
it with `pub use`), and each module's `use` imports (groups, renames, `self`, re-export chains inside
the crate), so `Url` written in a signature resolves to `url::Url`. Exposure sites: signatures of
public fns and methods (parameter and return types, generics, where clauses), public fields of
public structs, all variants of public enums, type aliases, const/static types, trait definitions
(supertraits, method signatures, associated types), trait impls for public types where the trait or a
type argument comes from a dependency (`impl From<dep::X> for MyType`, `impl dep::Trait for MyType`),
and `pub use dep::...` / `pub extern crate dep` re-exports. std/core/alloc are ignored; dependency
names come from Cargo.toml (renames via `package = ...`, `-` as `_`), dev and build dependencies are
ignored, and #[cfg(test)] code is skipped.

For each exposed dependency it reports the requirement, the locked version (Cargo.lock for a project;
the newest version matching the requirement for a published crate) and the latest release from the
live crates.io sparse index. Findings: medium pubdeps/exposed-outdated when a newer incompatible
release exists (upgrading it will break your users), medium pubdeps/unstable-dep-in-stable-api when a
crate at >= 1.0 exposes a 0.x dependency, info pubdeps/not-reexported when an exposed dependency is not
re-exported (suggests `pub use dep;` so users can name the exact version, or a newtype to hide it).
Cargo's unstable `public = true` dependency flag (RFC 1977, -Zpublic-dependency) lets the compiler
check this for you once stabilized; this tool works on stable today.

Limits: heuristic name resolution without macro expansion: items generated by macros, glob imports
from dependencies (`use dep::prelude::*`) and paths inside macro invocations are not seen; all
#[cfg] variants are included."
    }
    fn options(&self) -> &'static [Opt] {
        OPTS
    }
    fn examples(&self) -> &'static [&'static str] {
        &["sm-crates pubdeps", "sm-crates pubdeps reqwest@0.12.9", "sm-crates pubdeps tower-http --only http,bytes --json", "sm-crates pubdeps axum --max-items 10"]
    }
    fn requires(&self) -> &'static str {
        "network (crates.io sparse index; downloads named crates); cargo for local projects"
    }
    fn run(&self, ctx: &Ctx, args: &Args) -> Result<Report> {
        let (subject, targets) = apieco_util::lib_targets(ctx, args)?;
        let max_items: usize = args.parse_or("max-items", 5)?;
        let only: Vec<String> = args.list("only").iter().map(|s| util::normalize_crate_name(s)).collect();
        let mut rep = Report::new("pubdeps", subject);
        let mut table = Table::new("Exposed dependencies", &["Crate", "Dependency", "Exposures", "Kinds", "Requirement", "Locked", "Latest", "Breaking upgrade"]);
        let mut sites_table = Table::new("Exposure sites", &["Dependency", "Kind", "Public item", "Location", "Path"]);
        let mut data = Vec::new();
        let mut total_exposed = 0;
        let mut missing_all = Vec::new();
        for t in &targets {
            let dep_names: BTreeSet<String> = t.deps.iter().map(|d| d.extern_name.clone()).collect();
            let s = Surface::build(&t.dir, &t.lib, dep_names);
            missing_all.extend(s.missing_modules.iter().map(|m| format!("{}: {m}", t.name)));
            let display = |rel: &str| if t.local { util::rel(ctx.project_root(), &t.dir.join(rel)) } else { rel.to_string() };
            let mut exps = exposures(&s);
            for e in exps.iter_mut() {
                e.file = display(&e.file);
            }
            exps.retain(|e| only.is_empty() || only.contains(&util::normalize_crate_name(&e.dep)) || t.deps.iter().any(|d| d.extern_name == e.dep && only.contains(&util::normalize_crate_name(&d.package))));
            let mut per_dep: BTreeMap<String, Vec<Exposure>> = BTreeMap::new();
            for e in exps {
                per_dep.entry(e.dep.clone()).or_default().push(e);
            }
            let names: Vec<String> = per_dep
                .keys()
                .filter_map(|k| t.deps.iter().find(|d| &d.extern_name == k))
                .filter(|d| d.registry)
                .map(|d| d.package.clone())
                .collect();
            let idx = if names.is_empty() { BTreeMap::new() } else { index::versions_many(ctx, &names) };
            let own = util::parse_version(&t.version);
            let mut deps_json = Vec::new();
            for (ext, list) in &per_dep {
                let Some(d) = t.deps.iter().find(|d| &d.extern_name == ext) else { continue };
                total_exposed += 1;
                let latest = idx.get(&d.package).and_then(|v| v.as_ref()).and_then(|v| index::latest(v)).map(|v| v.vers.clone());
                let locked_v = d.locked.as_deref().and_then(util::parse_version);
                let latest_v = latest.as_deref().and_then(util::parse_version);
                let breaking = match (&locked_v, &latest_v) {
                    (Some(l), Some(n)) => n > l && util::semver_bucket(n) != util::semver_bucket(l),
                    _ => false,
                };
                let kinds = apieco_util::count_by(list.iter().map(|e| e.kind));
                let reexported_crate = list.iter().any(|e| e.kind == "re-export" && !e.path.contains("::"));
                let reexported_any = list.iter().any(|e| e.kind == "re-export");
                let kinds_txt = kinds.iter().map(|(k, n)| format!("{k} {n}")).collect::<Vec<_>>().join(", ");
                table.row([
                    t.name.clone(),
                    if d.package == d.extern_name.replace('_', "-") || d.package == d.extern_name { d.package.clone() } else { format!("{} (as {})", d.package, d.extern_name) },
                    list.len().to_string(),
                    kinds_txt.clone(),
                    d.req.clone(),
                    d.locked.clone().unwrap_or_else(|| "-".into()),
                    latest.clone().unwrap_or_else(|| if d.registry { "?".into() } else { "(not crates.io)".into() }),
                    if breaking { format!("yes ({})", latest.clone().unwrap_or_default()) } else { "no".into() },
                ]);
                let examples: Vec<String> = list.iter().take(3).map(|e| format!("{} ({}:{})", e.item, e.file, e.line)).collect();
                let first = &list[0];
                for e in list.iter().take(max_items) {
                    sites_table.row([d.package.clone(), e.kind.to_string(), e.item.clone(), format!("{}:{}", e.file, e.line), e.path.clone()]);
                }
                if breaking {
                    let l = latest.clone().unwrap_or_default();
                    rep.finding(
                        Finding::new(
                            Severity::Medium,
                            "pubdeps/exposed-outdated",
                            format!(
                                "{} is part of your public API ({} site(s)) and {} {l} is out; upgrading {} to {l} will be a breaking change for your users",
                                d.package,
                                list.len(),
                                d.package,
                                d.package
                            ),
                        )
                        .krate(&t.name, Some(&t.version))
                        .detail(format!("locked {}, requirement {}; exposed via {kinds_txt}; e.g. {}", d.locked.as_deref().unwrap_or("?"), d.req, examples.join("; ")))
                        .at(first.file.clone(), Some(first.line))
                        .fix(format!(
                            "Plan the {} upgrade together with your next breaking release, or hide it behind your own newtypes/traits so it can be upgraded in a minor release",
                            d.package
                        )),
                    );
                }
                if let (Some(own), Some(l)) = (&own, &locked_v) {
                    if own.major >= 1 && own.pre.is_empty() && l.major == 0 {
                        rep.finding(
                            Finding::new(
                                Severity::Medium,
                                "pubdeps/unstable-dep-in-stable-api",
                                format!("{} {} is stable (>= 1.0) but exposes pre-1.0 dependency {} {} in its public API", t.name, t.version, d.package, l),
                            )
                            .krate(&t.name, Some(&t.version))
                            .detail(format!("Every 0.x minor release of {} is breaking; e.g. {}", d.package, examples.join("; ")))
                            .at(first.file.clone(), Some(first.line))
                            .fix(format!("Wrap {} types in your own types, put the exposure behind an opt-in feature, or wait for {} 1.0", d.package, d.package)),
                        );
                    }
                }
                if !reexported_any {
                    rep.finding(
                        Finding::new(
                            Severity::Info,
                            "pubdeps/not-reexported",
                            format!("{} is exposed in {} public item(s) but not re-exported", d.package, list.len()),
                        )
                        .krate(&t.name, Some(&t.version))
                        .detail(format!("Users must add {} themselves at a compatible version to name these types; e.g. {}", d.package, examples.join("; ")))
                        .at(first.file.clone(), Some(first.line))
                        .fix(format!("Add `pub use {};` to the crate root so users get the exact version, or hide it behind a newtype", d.extern_name)),
                    );
                }
                deps_json.push(json!({
                    "dependency": d.package,
                    "extern_name": d.extern_name,
                    "requirement": d.req,
                    "optional": d.optional,
                    "locked": d.locked,
                    "latest": latest,
                    "breaking_upgrade": breaking,
                    "reexported": reexported_any,
                    "reexported_crate": reexported_crate,
                    "exposures": list.len(),
                    "kinds": kinds,
                    "sites": list.iter().map(|e| json!({"kind": e.kind, "item": e.item, "file": e.file, "line": e.line, "path": e.path})).collect::<Vec<_>>(),
                }));
            }
            let private_deps: Vec<String> = t.deps.iter().filter(|d| !per_dep.contains_key(&d.extern_name)).map(|d| d.package.clone()).collect();
            data.push(json!({
                "crate": t.name,
                "version": t.version,
                "public_items": s.reachable_items().filter(|i| !matches!(i.kind, ItemKind::Field | ItemKind::Variant)).count(),
                "exposed": deps_json,
                "private": private_deps,
            }));
        }
        let ndeps: usize = targets.iter().map(|t| t.deps.len()).sum();
        rep.table(table);
        rep.table(sites_table);
        rep.summary(format!(
            "{} of {} normal dependencies are part of the public API of {}",
            total_exposed,
            ndeps,
            targets.iter().map(|t| format!("{}@{}", t.name, t.version)).collect::<Vec<_>>().join(", ")
        ));
        if !missing_all.is_empty() {
            rep.note(format!("module files not found (generated or cfg-gated?): {}", missing_all.join(", ")));
        }
        rep.note("Heuristic source analysis without macro expansion: macro-generated items and glob imports from dependencies are not seen.");
        rep.note("Locked = Cargo.lock for a project; for a published crate, the newest release matching its requirement.");
        rep.data = json!({"crates": data});
        Ok(rep)
    }
}

/// Every exposure of a dependency in the public API of a modelled crate.
pub fn exposures(s: &Surface) -> Vec<Exposure> {
    let mut out: BTreeSet<Exposure> = BTreeSet::new();
    let mut push = |dep: String, kind: &'static str, item: String, file: usize, line: usize, path: &[String]| {
        out.insert(Exposure { dep, kind, item, file: s.file_rel(file).to_string(), line, path: path.join("::") });
    };
    let label = |i: &apieco_util::Item| -> String {
        match i.kind {
            ItemKind::Field => format!("field {}", i.display()),
            ItemKind::Variant => format!("variant {}", i.display()),
            k => format!("{} {}", k.as_str(), i.display()),
        }
    };
    let hidden = s.hidden();
    for it in s.reachable_items() {
        if matches!(it.kind, ItemKind::Mod | ItemKind::Macro) || hidden.of(it) {
            continue;
        }
        for site in &it.sites {
            for (p, line) in Surface::paths_in(&site.tokens) {
                if let Some((dep, full)) = s.resolve_dep(it.module, &p, 0) {
                    if full.len() < 2 {
                        continue; // the crate name itself (e.g. a parameter named like the crate)
                    }
                    push(dep, site.kind, label(it), it.file, line, &full);
                }
            }
        }
    }
    // trait impls that involve a public local type or trait
    for im in &s.impls {
        let Some(tr) = &im.trait_toks else { continue };
        if im.negative {
            continue;
        }
        let self_name = base_type_name(&im.self_toks);
        let self_paths = Surface::paths_in(&im.self_toks);
        let self_is_dep = self_paths.first().is_some_and(|(p, _)| s.resolve_dep(im.module, p, 0).is_some());
        let self_local = !self_is_dep && s.named_reachable(im.module, &self_name, false);
        let trait_name = base_type_name(tr);
        let trait_paths = Surface::paths_in(tr);
        let trait_is_dep = trait_paths.first().is_some_and(|(p, _)| s.resolve_dep(im.module, p, 0).is_some());
        let trait_local = !trait_is_dep && s.named_reachable(im.module, &trait_name, true);
        if !(self_local || trait_local) {
            continue;
        }
        let header = im.header();
        for toks in [tr.as_slice(), im.self_toks.as_slice(), im.bounds.as_slice()] {
            for (p, line) in Surface::paths_in(toks) {
                if let Some((dep, full)) = s.resolve_dep(im.module, &p, 0) {
                    if full.len() >= 2 {
                        push(dep, "impl", header.clone(), im.file, line, &full);
                    }
                }
            }
        }
    }
    // re-exports from reachable modules
    for (mi, m) in s.modules.iter().enumerate().filter(|(_, m)| m.reachable) {
        if hidden.mods.get(mi).copied().unwrap_or(false) {
            continue;
        }
        for u in m.uses.iter().filter(|u| u.vis == Vis::Pub) {
            if let Some((dep, full)) = s.resolve_dep(mi, &u.path, 0) {
                let what = if u.extern_crate {
                    format!("pub extern crate {}", u.path.join("::"))
                } else {
                    let tail = if u.glob { "::*".to_string() } else if u.path.last() != Some(&u.alias) { format!(" as {}", u.alias) } else { String::new() };
                    format!("pub use {}{tail}", u.path.join("::"))
                };
                let mut path = full.clone();
                if u.glob {
                    path.push("*".into());
                }
                push(dep, "re-export", what, u.file, u.line, &path);
            }
        }
    }
    let mut v: Vec<Exposure> = out.into_iter().collect();
    // strongest exposure first: re-exports, then by file/line
    v.sort_by(|a, b| (a.kind != "re-export").cmp(&(b.kind != "re-export")).then(a.file.cmp(&b.file)).then(a.line.cmp(&b.line)));
    v
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_exposures_and_ignores_private_uses() {
        let dir = util::temp_dir("pubdeps").unwrap();
        std::fs::create_dir_all(dir.join("src")).unwrap();
        std::fs::write(
            dir.join("src/lib.rs"),
            "use url::Url;\nuse regex::Regex;\npub use bytes::Bytes;\npub mod api;\n\
             pub struct Link { pub target: Url, cache: Regex }\n\
             fn private(r: Regex) {}\n\
             impl From<Url> for Link { fn from(u: Url) -> Self { todo!() } }\n\
             impl serde::Serialize for Link { fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> { todo!() } }\n\
             pub trait Source: http::HttpTrait { fn get(&self) -> http::Request<()>; }\n",
        )
        .unwrap();
        std::fs::write(dir.join("src/api.rs"), "pub fn parse(s: &str) -> Result<crate::Link, url::ParseError> { todo!() }\npub(crate) fn hidden(r: regex::Regex) {}\n").unwrap();
        let deps: BTreeSet<String> = ["url", "regex", "bytes", "serde", "http"].iter().map(|s| s.to_string()).collect();
        let s = Surface::build(&dir, &dir.join("src/lib.rs"), deps);
        let e = exposures(&s);
        let got: Vec<(String, &str, String)> = e.iter().map(|e| (e.dep.clone(), e.kind, e.path.clone())).collect();
        assert!(got.contains(&("bytes".into(), "re-export", "bytes::Bytes".into())), "{got:?}");
        assert!(got.contains(&("url".into(), "field", "url::Url".into())), "{got:?}");
        assert!(got.contains(&("url".into(), "impl", "url::Url".into())), "{got:?}");
        assert!(got.contains(&("serde".into(), "impl", "serde::Serialize".into())), "{got:?}");
        assert!(got.contains(&("http".into(), "bound", "http::HttpTrait".into())), "{got:?}");
        assert!(got.contains(&("http".into(), "signature", "http::Request".into())), "{got:?}");
        assert!(got.contains(&("url".into(), "signature", "url::ParseError".into())), "{got:?}");
        assert!(!got.iter().any(|g| g.0 == "regex"), "private uses must not count: {got:?}");
        assert_eq!(e[0].kind, "re-export");
        let _ = std::fs::remove_dir_all(dir);
    }

    #[test]
    fn doc_hidden_modules_are_not_public_api() {
        // like log's `#[doc(hidden)] pub mod __private_api;` used by its macros
        let dir = util::temp_dir("pubdeps-hidden").unwrap();
        std::fs::create_dir_all(dir.join("src/__private")).unwrap();
        std::fs::write(dir.join("src/lib.rs"), "#[doc(hidden)]\npub mod __private;\npub fn real(u: url::Url) {}\n").unwrap();
        std::fs::write(dir.join("src/__private/mod.rs"), "pub use regex::Regex;\npub fn capture(v: &dyn serde::Serialize) {}\npub mod deeper;\n").unwrap();
        std::fs::write(dir.join("src/__private/deeper.rs"), "pub struct S { pub b: bytes::Bytes }\n").unwrap();
        let deps: BTreeSet<String> = ["url", "regex", "serde", "bytes"].iter().map(|s| s.to_string()).collect();
        let s = Surface::build(&dir, &dir.join("src/lib.rs"), deps);
        let got: Vec<String> = exposures(&s).into_iter().map(|e| e.dep).collect();
        assert_eq!(got, ["url"]);
        let _ = std::fs::remove_dir_all(dir);
    }
}
